#!/usr/bin/env node
// Install agent skills that ship inside pinned npm devDependencies into
// .agents/skills (the copies are gitignored). package.json pins each package
// and Renovate bumps it, so the installed skill always matches the lockfile
// without a vendored copy or a symlink that dangles before install. Runs from
// postinstall. When a package is missing from node_modules (for example a
// production install without devDependencies), its stale copy is removed; an
// installed package that lacks an expected skill fails the install.
//
// modern-web-guidance's skill text, guides and CLI output tell agents to run
// `npx -y modern-web-guidance@latest` (or the bare `modern-web-guidance`
// binary), which would bypass the lockfile and its release-age policy. The
// CLI is bundled in the skill and needs only Node built-ins, so every
// invocation is rewritten to a generated guidance-only launcher in the copy,
// with telemetry off (skipping the upstream installer also skips its
// telemetry notice), and the npx/pnpx runner guidance is replaced. The copy
// is staged and checked first: an unpinned reference fails the install and
// leaves no copy behind.
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const skillsDir = path.join(root, '.agents', 'skills');

const CLI_PACKAGE = 'modern-web-guidance';
const CLI_SKILL = 'modern-web-guidance';
// The launcher is generated into the copy. The bundled CLI's
// install/update/uninstall commands treat every sibling directory in
// .agents/skills as one of its own skills (uninstall would pass the repo's
// skills to `npx skills remove`), so the launcher only admits guidance
// commands. Its absolute path works from any directory of this checkout; a
// root containing characters unsafe in shell or JS strings falls back to the
// repository-relative path.
const ENTRY = 'guidance.mjs';
const rootPosix = root.split(path.sep).join('/');
const ABSOLUTE_LAUNCHER = /^[\w./@+:-]+$/.test(rootPosix);
const LAUNCHER = ABSOLUTE_LAUNCHER
  ? `${rootPosix}/.agents/skills/${CLI_SKILL}/${ENTRY}`
  : `.agents/skills/${CLI_SKILL}/${ENTRY}`;
// The launcher sets DISABLE_TELEMETRY itself, so the command works unchanged
// in POSIX shells, PowerShell and cmd.
const LOCAL_CLI = `node ${LAUNCHER}`;
const GUIDANCE_COMMANDS = [
  'search',
  'list',
  'retrieve',
  'legacy-scan',
  'analyze',
  'set-baseline',
  'set-allow-origin-trials',
  'set-allow-volatile-features',
];

function launcherSource(version) {
  return `// Generated by tools/sync-package-skills.mjs: run only the guidance
// commands of the lockfile-pinned ${CLI_PACKAGE} ${version} CLI.
const commands = ${JSON.stringify(GUIDANCE_COMMANDS)};
process.env.DISABLE_TELEMETRY = "1";
const command = process.argv[2];
if (command === "-v" || command === "--version") {
  console.log(${JSON.stringify(version)});
  process.exit(0);
}
if (!command || command === "-h" || command === "--help") {
  console.log(${JSON.stringify(
    `Usage: ${LOCAL_CLI} <command> [args]\n\nCommands: ${GUIDANCE_COMMANDS.join(', ')}\n\n` +
      `The skill is installed from the repository lockfile; Renovate updates it.`,
  )});
  process.exit(command ? 0 : 1);
}
if (!commands.includes(command)) {
  console.error(\`${CLI_PACKAGE}: '\${command}' is not available here; the skill is managed by the repository's lockfile.\`);
  process.exit(2);
}
await import("./modern-web.mjs");
`;
}

const VERSION = String.raw`@(?:latest|next|v?\d[\w.-]*)`;
const RUNNER = String.raw`(?:(?:npx(?:\.cmd)?|pnpx|bunx)(?: --offline)?(?: -y)? |(?:pnpm|yarn) dlx |pnpm exec )`;
const COMMAND = String.raw`(?:${GUIDANCE_COMMANDS.join('|')}|install|uninstall|update)\b`;
// A runner-prefixed call (versioned or not, as in the CLI's own output), a
// bare versioned package reference, or the bare binary followed by a command.
// Marketplace names such as `modern-web-guidance@googlechrome` are not
// versions and stay as they are.
const RUNNER_INVOCATION = new RegExp(
  String.raw`(?:DISABLE_TELEMETRY=1 )?(?:${RUNNER}${CLI_PACKAGE}(?:${VERSION})?|${CLI_PACKAGE}${VERSION}|(?<![\w/.-])${CLI_PACKAGE}(?= ${COMMAND}))`,
  'g',
);
const SKILL_RUNNER_PROSE = /directly with `npx`/g;
const SKILL_RUNNER_MENTION = /\b(?:npx|pnpx|bunx|dlx)\b/;
const UNPINNED = new RegExp(
  String.raw`${CLI_PACKAGE}${VERSION}|\b(?:npx|pnpx|bunx|dlx)\b[^\n]{0,60}\b${CLI_PACKAGE}\b|(?<![\w/.-])${CLI_PACKAGE} ${COMMAND}`,
);
const RUNNER_SECTION = /^## Using npx \/ pnpx\n[\s\S]*?(?=^## )/m;
const LOCAL_RUNNER_SECTION = `## Running the CLI

- Run the CLI bundled with this skill${ABSOLUTE_LAUNCHER ? '' : ' from the repository root'}:
  \`${LOCAL_CLI} <command>\`. The
  repository's postinstall installs it from the lockfile-pinned
  \`${CLI_PACKAGE}\` devDependency; Renovate updates it.
- Do not fetch it with a package runner, which would bypass the pin. Search
  and retrieval read the bundled guides, so no network access is needed.

`;

/** Skills to install: [npm package, skill directory under its skills/]. */
const SKILLS = [[CLI_PACKAGE, CLI_SKILL]];

function textFiles(dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...textFiles(file));
    else if (!fs.readFileSync(file).includes(0)) out.push(file);
  }
  return out;
}

function pinCli(dir) {
  for (const file of textFiles(dir)) {
    const text = fs.readFileSync(file, 'utf8');
    let next = text.replace(RUNNER_INVOCATION, LOCAL_CLI);
    const isSkill = path.basename(file) === 'SKILL.md';
    if (isSkill) {
      next = next
        .replace(RUNNER_SECTION, LOCAL_RUNNER_SECTION)
        .replace(SKILL_RUNNER_PROSE, 'with the bundled CLI');
    }
    if (next !== text) fs.writeFileSync(file, next);
    const match =
      next.match(UNPINNED) || (isSkill && next.match(SKILL_RUNNER_MENTION));
    if (match) {
      throw new Error(
        `unpinned ${CLI_PACKAGE} runner remains in ${path.relative(dir, file)}: ${match[0]}`,
      );
    }
    if (/\.[cm]?js$/.test(file) && next !== text) {
      const check = spawnSync(process.execPath, ['--check', file], {
        encoding: 'utf8',
      });
      if (check.status !== 0) {
        throw new Error(
          `rewritten ${path.relative(dir, file)} no longer parses: ${check.stderr.trim()}`,
        );
      }
    }
  }
}

function syncSkills() {
  fs.mkdirSync(skillsDir, { recursive: true });
  const stage = fs.mkdtempSync(path.join(skillsDir, '.sync-'));
  const staged = [];
  try {
    // Stage and validate every skill before exposing any of them.
    for (const [pkg, skill] of SKILLS) {
      const pkgDir = path.join(root, 'node_modules', pkg);
      const src = path.join(pkgDir, 'skills', skill);
      if (!fs.existsSync(path.join(pkgDir, 'package.json'))) {
        staged.push([skill, null]); // package absent: drop any stale copy
        continue;
      }
      if (!fs.existsSync(path.join(src, 'SKILL.md'))) {
        throw new Error(`${pkg} is installed but has no skills/${skill}`);
      }
      const copy = path.join(stage, skill);
      fs.cpSync(src, copy, { recursive: true, dereference: true });
      if (skill === CLI_SKILL) {
        const { version } = JSON.parse(
          fs.readFileSync(path.join(pkgDir, 'package.json'), 'utf8'),
        );
        fs.writeFileSync(path.join(copy, ENTRY), launcherSource(version));
      }
      pinCli(copy);
      staged.push([skill, copy]);
    }
  } catch (error) {
    // Validation failed before anything was published: expose no copy.
    for (const [, skill] of SKILLS) {
      fs.rmSync(path.join(skillsDir, skill), { recursive: true, force: true });
    }
    fs.rmSync(stage, { recursive: true, force: true });
    throw error;
  }
  try {
    for (const [skill, copy] of staged) {
      const dest = path.join(skillsDir, skill);
      fs.rmSync(dest, { recursive: true, force: true });
      if (!copy) continue;
      try {
        fs.renameSync(copy, dest);
      } catch (error) {
        // A concurrent install of the same lockfile published first; its
        // copy is equivalent, so keep it rather than deleting it.
        if (error.code !== 'ENOTEMPTY' && error.code !== 'EEXIST') throw error;
      }
    }
  } finally {
    fs.rmSync(stage, { recursive: true, force: true });
  }
}

try {
  syncSkills();
} catch (error) {
  console.error(`sync-package-skills: ${error.message}; skills not installed`);
  process.exit(1);
}
